import fs from "node:fs";
import assert from "node:assert/strict";
import ts from "typescript";
const source = fs.readFileSync("src/lib/headerScroll.ts", "utf8");
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const module = { exports: {} };
new Function("exports", "module", compiled)(module.exports, module);
const { advanceHeaderScroll } = module.exports;
let state = { anchor: 0, previous: 0, direction: 0, visible: true };
const scroll = (y) => (state = advanceHeaderScroll(state, y)).visible;
assert.equal(scroll(20), true, "Visible near top");
assert.equal(scroll(100), false, "Hide scrolling down");
assert.equal(scroll(99), false, "Ignore tiny reversal");
assert.equal(scroll(92), true, "Show after upward movement");
assert.equal(scroll(93), true, "Ignore tiny downward movement");
assert.equal(scroll(101), false, "Hide when scrolling down again");
assert.equal(scroll(0), true, "Show at top");
assert.equal(scroll(-20), true, "Ignore negative overscroll");
assert.equal(scroll(0), true, "Remain visible after bounce");
console.log("PASS: header down/up, jitter threshold, page top and overscroll behavior.");
